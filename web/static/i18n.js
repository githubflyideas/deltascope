let currentLang = "en";

function t(key, ...args) {
  const dict = I18N[currentLang] || I18N.en;
  const val = dict[key] !== undefined ? dict[key] : I18N.en[key];
  if (val === undefined) return key;
  return typeof val === "function" ? val(...args) : val;
}

function detectLang() {
  try {
    const stored = localStorage.getItem("dscope-lang");
    if (stored && I18N[stored]) return stored;
  } catch (e) { /* private mode */ }
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  const short = nav.slice(0, 2);
  return I18N[short] ? short : "en";
}

function setLang(lang) {
  if (!I18N[lang]) lang = "en";
  currentLang = lang;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  try { localStorage.setItem("dscope-lang", lang); } catch (e) { /* private mode */ }
  applyStaticI18n();
}

// applyStaticI18n walks every element carrying a data-i18n attribute and
// sets its text (or placeholder, for data-i18n-placeholder) from the
// current language's dictionary. Called on load and whenever the
// language changes; dynamically-rendered content (tables, diagnosis
// results) reads t() directly at render time instead.
function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
}
